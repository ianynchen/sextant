#!/usr/bin/env bash
# CP-35 — where a Spring Cloud starter's version lives, and what spells it
# (spec 2026-10-17 §5a; plan Task 1 Step 1). Walks the BOM chain in the local
# Maven repository and prints the evidence table. Re-run it rather than trusting
# the write-up: `chain.py`'s output IS the measurement.
set -euo pipefail
cd "$(dirname "$0")"

PYTHON="${PYTHON:-../../../.venv/bin/python}"
[ -x "$PYTHON" ] || PYTHON="python3"

# The aggregating BOM this chain starts from. Passed in so the harness is re-runnable
# against another release; the COLUMN HEADER is not this value — see below.
ASKED="${BOM:-org.springframework.cloud:spring-cloud-dependencies:2025.1.0}"

TARGETS=(
  spring-cloud-starter-gateway-server-webflux
  spring-cloud-starter-netflix-eureka-client
  spring-cloud-starter-config
  spring-cloud-starter-circuitbreaker-reactor-resilience4j
)

OUT="$("$PYTHON" chain.py "$ASKED" "${TARGETS[@]}")"

# The identity check, and the reason this harness exists in this shape: the column
# header is the `<version>` `chain.py` READ OUT OF the pom it opened, not the version
# this script was asked for. CP-5 published eight cells for a version the process never
# ran, because the document and the harness both restated the parameter. A disagreement
# here aborts instead of printing a mislabelled column.
REPORTED="$(printf '%s\n' "$OUT" | awk '/^BOM-VERSION /{print $2}')"
WANTED="${ASKED##*:}"
if [ -z "$REPORTED" ]; then
  echo "chain.py reported no BOM version — refusing to print an unlabelled table" >&2
  exit 1
fi
if [ "$REPORTED" != "$WANTED" ]; then
  echo "the pom opened reports $REPORTED but $WANTED was requested — aborting" >&2
  exit 1
fi

echo "## Observations"
echo
echo "Generated by \`scripts/probes/cp35_bom_chain/run.sh\`. The column header is the"
echo "version the opened pom itself reported in its \`<version>\` element, not the version"
echo "passed in as \`BOM\` — the harness compares the two and aborts when they disagree."
echo
echo "| dependency | managed by | hops | ${REPORTED} |"
echo "|---|---|---|---|"
printf '%s\n' "$OUT" | awk -F'|' '
  /^ROW /{
    sub(/^ROW /, "", $1)
    printf "| `%s` | `%s` | %s | `%s` |\n", $1, $2, $3, $4
  }'
echo
echo "\`hops\` counts \`<parent>\` and \`<scope>import</scope>\` edges traversed from the"
echo "aggregating BOM. The last column is the RAW version string written at the managing"
echo "BOM — unexpanded, which is the finding."
