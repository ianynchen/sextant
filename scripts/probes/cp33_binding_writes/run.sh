#!/usr/bin/env bash
# CP-33 — what the bytecode shows for a binding assigned OUTSIDE an initialiser
# (capability 9.19, spec §4; plan Task 11 Step 1). Compiles `BindingWrites.java`
# and prints the instructions for every shape the capability would have to read
# and every one it must refuse. Re-run it rather than trusting the write-up:
# `javap`'s output IS the measurement.
set -euo pipefail
cd "$(dirname "$0")"

JAVA_BIN="${JAVA_HOME:-}/bin"
if [ ! -x "$JAVA_BIN/javac" ]; then
  echo "set JAVA_HOME to a JDK 21+ (javac and javap are both needed)" >&2
  exit 1
fi

# `@PostConstruct` only to show the annotation does not change the instructions.
echo "ensuring jakarta.annotation-api" >&2
mvn -q -B dependency:get -Dtransitive=false \
  -Dartifact="jakarta.annotation:jakarta.annotation-api:2.1.1" >/dev/null 2>&1 || true
JAR="$(find "$HOME/.m2" -name 'jakarta.annotation-api-2*.jar' 2>/dev/null | head -1)"

OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT
"$JAVA_BIN/javac" -cp "$JAR" -d "$OUT" BindingWrites.java

# The version column is read back from `javac -version`'s OWN output, never from
# $JAVA_HOME — labelling a cell with the toolchain we asked for rather than the one
# that answered is the CP-5 failure this harness exists not to repeat.
JAVAC_VERSION="$("$JAVA_BIN/javac" -version 2>&1 | awk '{print $2}')"
JAR_VERSION="$(basename "${JAR:-absent}" | sed -E 's/^jakarta\.annotation-api-//; s/\.jar$//')"

BYTECODE="$("$JAVA_BIN/javap" -c -p -cp "$OUT" probe.BindingWrites)"

# The generated evidence table: one row per shape, the cell being the instruction
# sequence between the method header and its `return`, as javap printed it.
emit_row () {  # $1 = label, $2 = javap method signature prefix
  # Only the numbered instruction lines, in order, opcode and operand kept and the
  # `#n  // comment` tail dropped. Joined with "; " by awk rather than by `paste -d`,
  # whose delimiter argument is a cycling LIST and silently alternated two separators.
  local seq
  seq="$(printf '%s\n' "$BYTECODE" | awk -v sig="$2" '
    index($0, sig) { found = 1; next }
    found && /^[[:space:]]*$/ { exit }
    found && match($0, /^[[:space:]]*[0-9]+: /) {
      line = substr($0, RSTART + RLENGTH)
      sub(/[[:space:]]+#[0-9]+.*$/, "", line)
      sub(/[[:space:]]+$/, "", line)
      out = out (out == "" ? "" : "; ") line
    }
    END { print out }')"
  printf '| %s | `%s` |\n' "$1" "$seq"
}

echo "## Observations"
echo
echo "Generated by \`scripts/probes/cp33_binding_writes/run.sh\`. The column header is the"
echo "version \`javac -version\` reported, not the parameter passed in as \`JAVA_HOME\`;"
echo "\`@PostConstruct\` came from jakarta.annotation-api ${JAR_VERSION}."
echo
echo "| shape | ${JAVAC_VERSION} |"
echo "|---|---|"
emit_row "a setter assigning its parameter"        "public void setViaSetter(java.lang.String);"
emit_row "\`@PostConstruct\` assigning a literal"  "public void init();"
emit_row "a computed assignment"                   "public void setComputed(java.lang.String, java.lang.String);"
emit_row "write then read the same field"          "public void writeThenRead(java.lang.String);"
emit_row "a second parameter after a \`long\`"     "public void setSecond(long, java.lang.String);"
emit_row "a static initialiser"                    "static {};"
emit_row "a field assigned a CALL's result"          "public void setFromCall(java.util.List<java.lang.String>);"
emit_row "an instance field INITIALISER"             "public probe.BindingWrites();"
echo
echo "Full \`javap\` output follows, so a reader can check the extraction above."
echo
printf '%s\n' "$BYTECODE"
