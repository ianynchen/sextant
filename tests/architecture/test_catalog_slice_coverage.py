"""A catalog says how much of its framework it reads, or it claims all of it
(GUIDELINES §2, §8; F2 §3.8).

## The problem this exists for

`spring-jms-template.yml` reads ONE of the 37 methods `JmsTemplate` declares, ten of
which take a destination name. `aws-sqs-sdk.yml` reads ONE of `SqsClient`'s 29, and
the 24 it does not read include `receiveMessage` — the entire inbound direction.
Neither file said so. A consumer reading the catalog list sees "JMS: supported" and
"SQS: supported", and there is nothing in the tree that would have told them
otherwise.

**Presence has to stop meaning completeness.** That is not achievable with a prose
paragraph, because a paragraph written once decays silently: the framework adds a
method, the catalog does not, and the paragraph still reads correctly. So the slice is
a declared key with a mechanical check.

## What this checks, and against what

`scripts/probes/w19_catalog_surface.md` section 3 is generated by
`scripts/probes/w19_catalog_surface/run.sh`, which enumerates each owner's declared
methods out of the jar's own bytecode and cross-references the catalog AS LOADED. Every
row in that table is a method the framework declares, the catalog does not read, and
which can address a wire — by taking a name at argument 0, or by taking a request
object the way the AWS SDK does.

Every one of those rows must be named in its catalog's `slice.outside`, with a reason.
The check runs both ways: a slice naming a method the enumeration does not list is
stale, and stale is how a slice stops being true without anybody noticing.

## What it cannot check

That the REASON is correct. "not a boundary" and "a boundary we do not model" are both
accepted here, and only a reader can tell whether the right one was chosen. What this
holds is that a choice was made, in the file, for every method — and that a release
adding an addressable method makes some test fail rather than quietly widening the
distance between what a catalog claims and what it reads.
"""

import re
from pathlib import Path

from sextant.ingress.catalogs.yaml_source import YamlCatalogSource

REPO = Path(__file__).parents[2]
CATALOGS = REPO / "src" / "sextant" / "catalogs"
PROBE = REPO / "scripts" / "probes" / "w19_catalog_surface.md"

# The generated table's own header, matched in full — a header that has drifted means
# the columns below are being read positionally against something else. The same
# discipline `test_catalog_descriptors.py` applies to CP-10's table.
_HEADER = "| catalog | owner | method | addressed by |"
_BACKTICKED = re.compile(r"^`(.*)`$")


def _cell(text: str) -> str:
    stripped = text.strip()
    match = _BACKTICKED.match(stripped)
    return match.group(1) if match else stripped


def enumerated() -> set[tuple[str, str, str]]:
    """`(catalog, owner, method)` for every unread candidate the probe measured."""
    lines = PROBE.read_text(encoding="utf-8").splitlines()
    start = next((i for i, line in enumerate(lines) if line.strip() == _HEADER), None)
    assert start is not None, (
        f"{PROBE.relative_to(REPO)} carries no slice table with the header its harness "
        f"generates:\n  {_HEADER}\nRe-run scripts/probes/w19_catalog_surface/run.sh and "
        f"paste its third table in verbatim."
    )
    rows: set[tuple[str, str, str]] = set()
    for line in lines[start + 2 :]:
        if not line.startswith("|"):
            break
        cells = [_cell(cell) for cell in line.split("|")[1:-1]]
        if len(cells) != 4:
            continue
        rows.add((cells[0], cells[1], cells[2]))
    assert rows, f"{PROBE.relative_to(REPO)}'s slice table parsed to no rows"
    return rows


def declared() -> set[tuple[str, str, str]]:
    """`(catalog, owner, method)` for every entry the shipped catalogs declare
    outside their slice."""
    rows: set[tuple[str, str, str]] = set()
    for catalog in YamlCatalogSource(CATALOGS).load():
        for entry in catalog.slice_outside:
            for method in entry["method_names"]:  # type: ignore[union-attr]
                rows.add((catalog.id, str(entry["owner"]), str(method)))
    return rows


def test_every_unread_addressable_method_is_named_outside_the_slice():
    """The rule. A method the framework declares, that can address a wire, and that
    the catalog does not read, is either declared outside the slice or it is an
    undisclosed gap — and an undisclosed gap is exactly what "supported" meant
    before this file existed."""
    undisclosed = sorted(enumerated() - declared())
    assert undisclosed == [], (
        "these methods can address a wire, are not read by the catalog, and are not "
        "declared outside its slice:\n"
        + "\n".join(f"  - {catalog}: {owner}#{method}" for catalog, owner, method in undisclosed)
        + "\n\nDeclare each in that catalog's `slice.outside` with a reason, or read it. "
        "Leaving it out means the catalog claims a surface it does not have."
    )


def test_no_slice_names_a_method_the_enumeration_does_not_list():
    """The other direction, and the one that keeps the first honest over time. A
    slice entry for a method the framework no longer declares — renamed, removed, or
    now READ by this catalog — is stale, and a stale slice understates coverage as
    confidently as a missing one overstates it."""
    stale = sorted(declared() - enumerated())
    assert stale == [], (
        "these `slice.outside` entries name methods the enumeration does not list as "
        "unread candidates:\n"
        + "\n".join(f"  - {catalog}: {owner}#{method}" for catalog, owner, method in stale)
        + "\n\nEither the catalog now reads it (drop the entry), or the framework no "
        "longer declares it (drop the entry and re-run the probe), or the owner is "
        "spelled differently here than in the enumeration."
    )
