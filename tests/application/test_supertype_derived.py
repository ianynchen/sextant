"""Tests for the `supertype_derived` engine (D02 §2's `supertype_derived`
style, 2O design §1b, Task 5).

Facts are hand-built to mirror CP-8's real, checkpoint-recorded shapes
exactly (`scripts/probes/cp3_cp8_grpc_facts.md`, against the real,
checked-in `fixtures/grpc-probe/`) — protoc's generated `<Service>Grpc`
class builds its `ServiceDescriptor`/`MethodDescriptor` identities through
`ServiceDescriptor.newBuilder("<protoPackage>.<Service>")` and
`MethodDescriptor.generateFullMethodName(SERVICE_NAME, "<Method>")`, both
STATIC methods declared directly on the outer generated class, never on the
nested `<Service>ImplBase` a real implementer extends — rather than compiling
and scanning real bytecode for every case, which is exactly what
`fixtures/grpc-probe`'s own checkpoint already did once (R11's own citation).

Every identity string below is invented (`orders.v1.OrderService`, never
`sextant.orders.OrderService`) — the shipped catalog's live answer against
real generated bytecode belongs to `fixtures/grpc-probe`/its checkpoint, not
here (the `test_schema_operations.py` precedent this file otherwise
mirrors)."""

import json
from pathlib import Path

from sextant.application.ports.catalogs import Catalog, CatalogSource
from sextant.application.resolve.endpoints import derive_endpoints
from sextant.application.resolve.pipeline import resolve
from sextant.domain.closed_sets import ConstructKind, OriginTier
from sextant.domain.factfile import write_fact_file
from sextant.domain.facts import (
    CallArgument,
    CallSiteFact,
    CallTarget,
    DeclaredShapeFact,
    Document,
    OperationRecord,
    SymbolFact,
)
from sextant.storage.duckdb.workspace import DuckDbWorkspace

CAPABILITIES = {"call_site", "string_constants", "superclass"}
# The module-coordinates prefix a real symbol fact's own `symbol` carries
# (D00 §5a) — `test_interface_engine.py`'s own `_MODULE` precedent.
_MODULE = "sextant-jvm maven com.acme/grpc-probe 1.0.0 "

OUTER = "com/acme/grpcprobe/proto/OrderServiceGrpc#"
IMPL_BASE = "com/acme/grpcprobe/proto/OrderServiceGrpc$OrderServiceImplBase#"
IMPLEMENTOR = "com/acme/grpcprobe/OrderServiceImpl#"
SERVICE_NAME = "orders.v1.OrderService"


class _Catalogs(CatalogSource):
    """A CatalogSource over catalogs a test built by hand — the seam D02 §6
    exists for (`test_pipeline.py`'s own `_Catalogs` precedent, duplicated
    here rather than imported: every engine test file keeps its own copy)."""

    def __init__(self, catalogs: list[Catalog]) -> None:
        self._catalogs = catalogs

    def load(self) -> list[Catalog]:
        return self._catalogs


def _document(document_id: str = "doc_1") -> Document:
    return Document(
        document_id=document_id,
        relative_path="com/acme/grpcprobe/OrderServiceImpl.java",
        module_id="com.acme:grpc-probe",
        language="java",
        sextant_version="0.1.0",
        fact_schema_version="1.0.0",
        scanner_id="asm",
        scanner_version="9.14",
        content_hash="sha256:a",
        origin_entry="target/classes",
        origin_tier=OriginTier.MODULE_OUTPUT,
        redaction_set_hash="sha256:b",
    )


def _supertype_facts(*method_names: str) -> list[SymbolFact]:
    """The generated `<Service>ImplBase`'s own class fact, plus one declared
    method per name — capability 9.13's `superclass` join target
    (`supertype_derived._matches`'s own "the extends target is itself in the
    module's facts" test) needs the class fact to exist at all; the method
    facts are what `overridden_public_methods` compares an implementer's own
    declared methods against."""
    facts: list[SymbolFact] = [
        SymbolFact(
            document_id="doc_1", symbol=_MODULE + IMPL_BASE, construct_kind=ConstructKind.CLASS
        )
    ]
    for name in method_names:
        facts.append(
            SymbolFact(
                document_id="doc_1",
                symbol=f"{_MODULE}{IMPL_BASE}{name}(sig_base).",
                construct_kind=ConstructKind.METHOD,
                enclosing=_MODULE + IMPL_BASE,
            )
        )
    return facts


def _implementor_facts(*method_names: str, superclass: str | None = None) -> list[SymbolFact]:
    """One implementing class extending the generated base (`superclass`
    defaults to `IMPL_BASE`, module-prefixed exactly as capability 9.13's
    real emitted fact carries it — CP-8(c)), plus one PUBLIC override per
    name (`SymbolFact.visibility` defaults `"public"`, D00 §5a)."""
    facts: list[SymbolFact] = [
        SymbolFact(
            document_id="doc_1",
            symbol=_MODULE + IMPLEMENTOR,
            construct_kind=ConstructKind.CLASS,
            superclass=_MODULE + (superclass or IMPL_BASE),
        )
    ]
    for name in method_names:
        facts.append(
            SymbolFact(
                document_id="doc_1",
                symbol=f"{_MODULE}{IMPLEMENTOR}{name}(sig_impl).",
                construct_kind=ConstructKind.METHOD,
                enclosing=_MODULE + IMPLEMENTOR,
            )
        )
    return facts


def _service_name_site(value: str | None = SERVICE_NAME, *, ordinal: int = 0) -> CallSiteFact:
    """CP-8(b)'s own `ServiceDescriptor.newBuilder("<protoPackage>.<Service>")`
    call, declared on the OUTER generated class (`getServiceDescriptor`),
    never on the nested `ImplBase` an implementer extends."""
    return CallSiteFact(
        document_id="doc_1",
        caller=f"{_MODULE}{OUTER}getServiceDescriptor().",
        target=CallTarget(
            owner="io/grpc/ServiceDescriptor#", name="newBuilder", descriptor="(...)V"
        ),
        invoke_kind="static",
        ordinal=ordinal,
        arguments=[
            CallArgument(kind="string", value=value)
            if value is not None
            else CallArgument(kind="unresolved")
        ],
    )


def _method_name_site(
    wire_method: str, *, service: str = SERVICE_NAME, accessor: str | None = None, ordinal: int = 1
) -> CallSiteFact:
    """CP-8(d)'s own
    `MethodDescriptor.generateFullMethodName(SERVICE_NAME, "<Method>")` call
    — one per RPC method, declared as its own `get<Method>Method()` accessor
    on the SAME outer class."""
    return CallSiteFact(
        document_id="doc_1",
        caller=f"{_MODULE}{OUTER}{accessor or f'get{wire_method}Method'}().",
        target=CallTarget(
            owner="io/grpc/MethodDescriptor#", name="generateFullMethodName", descriptor="(...)V"
        ),
        invoke_kind="static",
        ordinal=ordinal,
        arguments=[
            CallArgument(kind="string", value=service),
            CallArgument(kind="string", value=wire_method),
        ],
    )


def _catalog(
    *, matches: dict[str, object] | None = None, source: str = "test-grpc-java.yml"
) -> Catalog:
    if matches is None:
        matches = {
            "supertype_marker": {
                "service_name_call": {"owner": "io.grpc.ServiceDescriptor", "method": "newBuilder"},
                "method_name_call": {
                    "owner": "io.grpc.MethodDescriptor",
                    "method": "generateFullMethodName",
                },
            },
            "members": "overridden_public_methods",
        }
    return Catalog(
        id="test-grpc-java",
        style="supertype_derived",
        protocol="grpc",
        direction="inbound",
        requires=("call_site", "string_constants", "superclass"),
        matches=matches,
        source=Path(source),
    )


def _resolve(tmp_path: Path, facts: list, catalog: Catalog | None = None) -> DuckDbWorkspace:
    write_fact_file(tmp_path / "facts" / "Client.jsonl", _document(), facts)
    workspace = DuckDbWorkspace(tmp_path / "ws.duckdb")
    workspace.load_facts(tmp_path / "facts")
    skipped = derive_endpoints(workspace, [catalog or _catalog()], capabilities=CAPABILITIES)
    assert skipped == []
    return workspace


# --- (a) one row per overridden method, wire name read verbatim ------------


def test_an_implementation_derives_one_row_per_overridden_method(tmp_path: Path):
    facts = [
        *_supertype_facts("getOrder", "streamOrders"),
        *_implementor_facts("getOrder", "streamOrders"),
        _service_name_site(),
        _method_name_site("GetOrder"),
        _method_name_site("StreamOrders", accessor="getStreamOrdersMethod", ordinal=2),
    ]
    workspace = _resolve(tmp_path, facts)
    rows = {row["path"]: row for row in workspace.query("endpoints")}
    workspace.close()

    assert set(rows) == {
        f"{SERVICE_NAME}/GetOrder",
        f"{SERVICE_NAME}/StreamOrders",
    }
    get_order = rows[f"{SERVICE_NAME}/GetOrder"]
    assert get_order["protocol"] == "grpc"
    assert get_order["direction"] == "inbound"
    assert get_order["method"] is None
    # The identity comes from the generated class's own call-site constants
    # and its wire method-name constant — never from casing the Java method
    # name, which is not invertible (R11).
    assert get_order["handler"] == f"{_MODULE}{IMPLEMENTOR}getOrder(sig_impl)."
    assert get_order["resolution"] == "resolved"
    assert get_order["request_shape"] is None and get_order["response_shape"] is None


def test_a_method_the_implementer_does_not_override_derives_no_row(tmp_path: Path):
    """`overridden_public_methods` is evidence-shaped: the generated base
    declares two RPC methods, the implementer overrides only one, and the
    wire method-name constants for BOTH are readable — only the actually
    overridden one derives."""
    facts = [
        *_supertype_facts("getOrder", "streamOrders"),
        *_implementor_facts("getOrder"),
        _service_name_site(),
        _method_name_site("GetOrder"),
        _method_name_site("StreamOrders", accessor="getStreamOrdersMethod", ordinal=2),
    ]
    workspace = _resolve(tmp_path, facts)
    rows = workspace.query("endpoints")
    workspace.close()

    assert [row["path"] for row in rows] == [f"{SERVICE_NAME}/GetOrder"]


def test_a_class_extending_the_base_without_overriding_anything_derives_nothing(tmp_path: Path):
    """ "The registration is the evidence" restated for a style reached by
    `extends`: a class merely extending the generated base, overriding none
    of its methods, proves nothing this style derives from."""
    facts = [
        *_supertype_facts("getOrder"),
        *_implementor_facts(),
        _service_name_site(),
        _method_name_site("GetOrder"),
    ]
    workspace = _resolve(tmp_path, facts)
    rows = workspace.query("endpoints")
    workspace.close()

    assert rows == []


def test_a_stub_from_a_published_jar_derives_nothing_not_even_unresolved(tmp_path: Path):
    """The stated boundary (2O design §1b): the extends EDGE is this class's
    own fact regardless, but the target's own facts (no `_supertype_facts()`
    here) never reached this workspace, so nothing proves it is a gRPC
    service at all — not even the unresolved fallback, which is reserved for
    a LOCALLY SEEN supertype whose marker calls could not be read."""
    facts = [*_implementor_facts("getOrder")]
    workspace = _resolve(tmp_path, facts)
    rows = workspace.query("endpoints")
    workspace.close()

    assert rows == []


# --- (b) unreadable identity: unresolved fallback, never a fabricated path -


def test_an_unresolvable_identity_derives_the_unresolved_fallback_row(tmp_path: Path):
    """CP-8(b)/(d) falsifying (no `ServiceDescriptor.newBuilder` call site
    reaches the outer class at all): the row still derives — D02 §2's
    unresolved-is-an-answer — with `path` the supertype's own bare
    descriptor verbatim, never a fabricated package."""
    facts = [*_supertype_facts("getOrder"), *_implementor_facts("getOrder")]
    workspace = _resolve(tmp_path, facts)
    [row] = workspace.query("endpoints")
    workspace.close()

    assert row["path"] == IMPL_BASE
    assert row["resolution"] == "unresolved"
    assert row["handler"] is None


def test_an_unreadable_identity_files_a_question_rather_than_guessing(tmp_path: Path):
    """The `service_identity` open-question ledger row (2G design §6, 2O
    design §1b) — filed by `resolve/service_identity.py`'s own pass, AFTER
    the 2K ledger reset, which is why this test runs the full pipeline
    (`resolve()`) rather than `derive_endpoints` alone."""
    facts = [*_supertype_facts("getOrder"), *_implementor_facts("getOrder")]
    write_fact_file(tmp_path / "facts" / "Client.jsonl", _document(), facts)
    workspace = DuckDbWorkspace(tmp_path / "ws.duckdb")
    resolve(workspace, tmp_path / "facts", _Catalogs([_catalog()]), CAPABILITIES)
    questions = workspace.query("open_questions")
    workspace.close()

    assert len(questions) == 1
    assert questions[0]["question"] == "service_identity"
    assert questions[0]["path"] == IMPL_BASE
    candidates = json.loads(str(questions[0]["candidates"]))
    assert candidates[0]["class"] == _MODULE + IMPLEMENTOR


# --- (c) the descriptor and bytecode rows merge on the real wire identity --


def test_the_bytecode_row_merges_with_the_descriptor_row(tmp_path: Path):
    """Both sides derive the same `(protocol, direction, method, path)` by
    construction, so D01's only join collapses them into one row — the
    descriptor's own `schema_operations` row and this style's own row never
    coexist at the same identity (`derive_call_endpoints.sql`'s
    insert-if-absent). `supertype_derived` is NOT in `_RUNS_LAST`
    (`resolve/endpoints.py`), so it inserts FIRST; `schema_operations` is,
    so its own attempt at the identical identity is a no-op — the bytecode
    row's `handler` is what survives, the descriptor's own
    `request_shape`/`response_shape` are not (a known, accepted consequence
    of R11's own design, `schema_operations.py`'s own docstring: "gRPC's row
    above already CARRIES its own `response_shape`, so stamping it would
    only ever find a row that has nothing to coalesce")."""
    path = f"{SERVICE_NAME}/GetOrder"
    shape = DeclaredShapeFact(
        document_id="doc_1",
        symbol=path,
        schema_name=path,
        schema_format="protobuf",
        origin="source",
        evidence="declared",
        role="operation",
        operation=OperationRecord(
            input_ref="orders.v1.GetOrderRequest",
            output_ref="orders.v1.GetOrderReply",
            client_streaming=False,
            server_streaming=False,
        ),
    )
    schema_catalog = Catalog(
        id="test-grpc-schema",
        style="schema_operations",
        protocol="grpc",
        direction="inbound",
        requires=(),
        matches={
            "schema_operations": {
                "schema_format": "protobuf",
                "operations": {"operation": "operation"},
            }
        },
        source=Path("test-grpc-schema.yml"),
    )
    facts = [
        *_supertype_facts("getOrder"),
        *_implementor_facts("getOrder"),
        _service_name_site(),
        _method_name_site("GetOrder"),
        shape,
    ]
    write_fact_file(tmp_path / "facts" / "Client.jsonl", _document(), facts)
    workspace = DuckDbWorkspace(tmp_path / "ws.duckdb")
    workspace.load_facts(tmp_path / "facts")
    skipped = derive_endpoints(workspace, [_catalog(), schema_catalog], capabilities=CAPABILITIES)
    assert skipped == []
    rows = workspace.query("endpoints")
    workspace.close()

    assert len(rows) == 1
    assert rows[0]["path"] == path
    assert rows[0]["handler"] == f"{_MODULE}{IMPLEMENTOR}getOrder(sig_impl)."
