IMPLEMENTOR = "com/acme/grpcprobe/OrderServiceImpl#"
SERVICE_NAME = "orders.v1.OrderService"


class _Catalogs(CatalogSource):
    """A CatalogSource over catalogs a test built by hand — the seam D02 §6
    exists for (`test_pipeline.py`'s own `_Catalogs` precedent, duplicated
    here rather than imported: every engine test file keeps its own copy)."""

    def __init__(self, catalogs: list[Catalog]) -> None:
        self._catalogs = catalogs

    def load(self) -> list[Catalog]:
        return self._catalogs


def _document(document_id: str = "doc_1") -> Document:
    return Document(
        document_id=document_id,
        relative_path="com/acme/grpcprobe/OrderServiceImpl.java",
        module_id="com.acme:grpc-probe",
        language="java",
        sextant_version="0.1.0",
        fact_schema_version=2,
        scanner_id="asm",
        content_hash="sha256:a",
        origin_entry="target/classes",
        origin_tier=OriginTier.MODULE_OUTPUT,
        redaction_set_hash="sha256:b",
    )


def _supertype_facts(*method_names: str) -> list[SymbolFact]:
    """The generated `<Service>ImplBase`'s own class fact, plus one declared
    method per name — capability 9.13's `superclass` join target
    (`supertype_derived._matches`'s own "the extends target is itself in the
    module's facts" test) needs the class fact to exist at all; the method
    facts are what `overridden_public_methods` compares an implementer's own
    declared methods against."""
    facts: list[SymbolFact] = [
        SymbolFact(
            document_id="doc_1", symbol=_MODULE + IMPL_BASE, construct_kind=ConstructKind.CLASS
        )
    ]
    for name in method_names:
        facts.append(
            SymbolFact(
                document_id="doc_1",
                symbol=f"{_MODULE}{IMPL_BASE}{name}(sig_base).",
                construct_kind=ConstructKind.METHOD,
                enclosing=_MODULE + IMPL_BASE,
            )
        )
    return facts


def _implementor_facts(*method_names: str, superclass: str | None = None) -> list[SymbolFact]:
    """One implementing class extending the generated base (`superclass`
    defaults to `IMPL_BASE`, module-prefixed exactly as capability 9.13's
    real emitted fact carries it — CP-8(c)), plus one PUBLIC override per
    name (`SymbolFact.visibility` defaults `"public"`, D00 §5a)."""
    facts: list[SymbolFact] = [
        SymbolFact(
            document_id="doc_1",
            symbol=_MODULE + IMPLEMENTOR,
            construct_kind=ConstructKind.CLASS,
            superclass=_MODULE + (superclass or IMPL_BASE),
        )
    ]
    for name in method_names:
        facts.append(
            SymbolFact(
                document_id="doc_1",
                symbol=f"{_MODULE}{IMPLEMENTOR}{name}(sig_impl).",
                construct_kind=ConstructKind.METHOD,
                enclosing=_MODULE + IMPLEMENTOR,
            )
        )
    return facts


def _service_name_site(
    value: str | None = SERVICE_NAME, *, ordinal: int = 0, outer: str = OUTER
) -> CallSiteFact:
    """CP-8(b)'s own `ServiceDescriptor.newBuilder("<protoPackage>.<Service>")`
    call, declared on the OUTER generated class (`getServiceDescriptor`),
    never on the nested `ImplBase` an implementer extends."""
    return CallSiteFact(
        document_id="doc_1",
        caller=f"{_MODULE}{outer}getServiceDescriptor().",
        target=CallTarget(
            owner="io/grpc/ServiceDescriptor#", name="newBuilder", descriptor="(...)V"
        ),
        invoke_kind="static",
        ordinal=ordinal,
        arguments=[
            CallArgument(kind="string", value=value)
            if value is not None
            else CallArgument(kind="unresolved")
        ],
    )


def _method_name_site(
    wire_method: str,
    *,
    service: str = SERVICE_NAME,
    accessor: str | None = None,
    ordinal: int = 1,
    outer: str = OUTER,
) -> CallSiteFact:
    """CP-8(d)'s own
    `MethodDescriptor.generateFullMethodName(SERVICE_NAME, "<Method>")` call
    — one per RPC method, declared as its own `get<Method>Method()` accessor
    on the SAME outer class."""
    return CallSiteFact(
        document_id="doc_1",
        caller=f"{_MODULE}{outer}{accessor or f'get{wire_method}Method'}().",
        target=CallTarget(
            owner="io/grpc/MethodDescriptor#", name="generateFullMethodName", descriptor="(...)V"
        ),
        invoke_kind="static",
        ordinal=ordinal,
        arguments=[
            CallArgument(kind="string", value=service),
            CallArgument(kind="string", value=wire_method),
        ],
    )


def _catalog(
    *, matches: dict[str, object] | None = None, source: str = "test-grpc-java.yml"
) -> Catalog:
    if matches is None:
        matches = {
            "supertype_marker": {
                "service_name_call": {"owner": "io.grpc.ServiceDescriptor", "method": "newBuilder"},
                "method_name_call": {
                    "owner": "io.grpc.MethodDescriptor",
                    "method": "generateFullMethodName",
                },
            },
            "members": "overridden_public_methods",
        }
    return Catalog(
        id="test-grpc-java",
        style="supertype_derived",
        protocol="grpc",
        direction="inbound",
        requires=("call_site", "string_constants", "superclass"),
        matches=matches,
        source=Path(source),
    )


def _resolve(tmp_path: Path, facts: list, catalog: Catalog | None = None) -> DuckDbWorkspace:
    write_fact_file(tmp_path / "facts" / "Client.jsonl", _document(), facts)
    workspace = DuckDbWorkspace(tmp_path / "ws.duckdb")
    workspace.load_facts(tmp_path / "facts")
    skipped = derive_endpoints(workspace, [catalog or _catalog()], capabilities=CAPABILITIES)
    assert skipped == []
    return workspace


# --- (a) one row per overridden method, wire name read verbatim ------------


def test_an_implementation_derives_one_row_per_overridden_method(tmp_path: Path):
    facts = [
        *_supertype_facts("getOrder", "streamOrders"),
        *_implementor_facts("getOrder", "streamOrders"),
        _service_name_site(),
        _method_name_site("GetOrder"),
        _method_name_site("StreamOrders", accessor="getStreamOrdersMethod", ordinal=2),
    ]
    workspace = _resolve(tmp_path, facts)
    rows = {row["path"]: row for row in workspace.query("endpoints")}
    workspace.close()

    assert set(rows) == {
        f"{SERVICE_NAME}/GetOrder",
        f"{SERVICE_NAME}/StreamOrders",
    }
    get_order = rows[f"{SERVICE_NAME}/GetOrder"]
    assert get_order["protocol"] == "grpc"
    assert get_order["direction"] == "inbound"
    assert get_order["method"] is None
    # The identity comes from the generated class's own call-site constants
    # and its wire method-name constant — never from casing the Java method
    # name, which is not invertible (R11).
    assert get_order["handler"] == f"{_MODULE}{IMPLEMENTOR}getOrder(sig_impl)."
    assert get_order["resolution"] == "resolved"
    assert get_order["request_shape"] is None and get_order["response_shape"] is None


